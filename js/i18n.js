const STORAGE_KEY = "glotti.uiLang";
const RTL = new Set(["ar"]);

export function siteLang(code) {
  const raw = String(code || "en").toLowerCase().split("-")[0];
  return raw in LOCALES ? raw : "en";
}

export function isRtl(code) {
  return RTL.has(siteLang(code));
}

export function t(key, lang, vars = {}) {
  const locale = siteLang(lang);
  let text = LOCALES[locale]?.[key] ?? EN[key] ?? String(key);
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function detectSiteLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved) return siteLang(saved);
  } catch {
    /* Private mode can block storage. */
  }
  return siteLang(navigator.language);
}

export function saveSiteLang(lang) {
  const next = siteLang(lang);
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    /* Ignore quota / private mode. */
  }
  return next;
}
